import { test, expect } from "@playwright/test";
import { newProject } from "../shared/project";
import { initialWorkflow } from "../shared/workflow";

test("live FPS measures completed scene work and clears on pause", async ({ page }) => {
  const project = newProject();
  project.settings.fps = 60;
  project.html = '<div>Slow scene</div>';
  project.css = '';
  project.js = 'window.renderFrame = () => { const start = performance.now(); while (performance.now() - start < 65) {} };';
  await page.route("**/api/workspaceGet", r => r.fulfill({ json: { result: project } }));
  await page.route("**/api/settingsGet", r => r.fulfill({ json: { result: {} } }));
  await page.route("**/api/autosave", r => r.fulfill({ json: { result: true } }));
  await page.goto("/#editor");
  await page.getByRole("tab", { name: "Performance", exact: true }).click();
  const meter = page.getByLabel("Preview performance", { exact: true });
  await expect(meter).toContainText("Target 60 FPS");
  await expect(meter).toContainText("Preview paused");
  await expect(page.locator('.preview-area iframe').first()).toBeVisible();
  await page.locator('.transport .play-button').last().click();
  await expect(meter).toContainText(/Live \d+\.\d FPS/);
  await expect(meter).toHaveAttribute("data-slow", "true");
  await expect.poll(async () => {
    const text = await meter.innerText();
    const fps = Number(text.match(/Live ([\d.]+) FPS/)?.[1]);
    const render = Number(text.match(/([\d.]+) ms render/)?.[1]);
    return fps > 0 && fps < 25 && render >= 60;
  }).toBe(true);
  await page.locator('.transport .play-button').last().click();
  await expect(meter).toContainText("Preview paused");
  await expect(meter).not.toContainText("ms render");
});

test("inspector distinguishes project totals from the selected preview and quality", async ({ page }) => {
  const project = newProject();
  project.name = "Two timelines";
  project.settings = { ...project.settings, width: 3840, height: 2160, fps: 60 };
  project.workflow = initialWorkflow(project);
  project.workflow.scenes[0].title = "Opening timeline";
  project.workflow.scenes.push({ ...project.workflow.scenes[0], id: "scene-2", title: "Closing timeline", duration: 5 });
  await page.route("**/api/workspaceGet", r => r.fulfill({ json: { result: project } }));
  await page.route("**/api/settingsGet", r => r.fulfill({ json: { result: {} } }));
  await page.route("**/api/autosave", r => r.fulfill({ json: { result: true } }));
  await page.goto("/#editor");
  await expect(page.getByLabel("Project inspector")).toContainText("15.00s");
  await page.getByRole("tab", { name: "Preview", exact: true }).click();
  const details = page.getByRole("region", { name: "Current preview details", exact: true });
  const row = (name: string) => details.locator("dl > div").filter({ has: page.locator("dt", { hasText: new RegExp(`^${name}$`) }) });
  await expect(row("Viewing")).toContainText("Opening timeline");
  await expect(row("Scope")).toContainText("Selected timeline");
  await expect(row("Canvas")).toContainText("3840 × 2160 px");
  await expect(row("Duration")).toContainText("10.00 s");
  await page.getByLabel("Preview quality", { exact: true }).selectOption("full");
  await expect(row("3D quality")).toContainText("Full resolution");
  await expect(row("3D render target")).toContainText("3840 × 2160 px · 100%");
  await page.getByLabel("Preview quality", { exact: true }).selectOption("1080");
  await expect(row("3D render target")).toContainText("1920 × 1080 px · 50%");
  await page.getByLabel("Project inspector").screenshot({ path: "test-results/preview-details-inspector.png" });
  // Arrow navigation changes the active panel without putting hidden tabs in the focus order.
  const previewTab = page.getByRole("tab", { name: "Preview", exact: true });
  await previewTab.focus();
  await page.keyboard.press("ArrowRight");
  const performanceTab = page.getByRole("tab", { name: "Performance", exact: true });
  await expect(performanceTab).toBeFocused();
  await expect(performanceTab).toHaveAttribute("aria-selected", "true");
  await expect(details).toBeHidden();
  await expect(page.getByLabel("Preview performance", { exact: true })).toContainText("16.67 ms/frame");
  await page.getByLabel("Project inspector").screenshot({ path: "test-results/preview-performance-inspector.png" });
  await page.keyboard.press("Home");
  await expect(page.getByRole("tab", { name: "Project", exact: true })).toBeFocused();
  await expect(page.getByLabel("Project inspector")).toContainText("15.00s");
});
