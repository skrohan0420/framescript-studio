import { test, expect } from "@playwright/test";
import { newProject } from "../shared/project";
import { readReferenceConfig } from "../shared/reference-config";

test("project config preserves saved looks and stays independent of global defaults", async ({ page }) => {
  let workspace = newProject();
  workspace.promptDraft = { referenceStyle: "Legacy custom look", referenceNotes: "Keep copper", script: "An orbit" };
  let preferences: Record<string, unknown> = { referenceConfig: readReferenceConfig({ referenceNotes: "Global blue" }) };
  await page.route("**/api/workspaceGet", r => r.fulfill({ json: { result: workspace } }));
  await page.route("**/api/settingsGet", r => r.fulfill({ json: { result: preferences } }));
  await page.route("**/api/settingsSet", r => {
    preferences = { ...preferences, ...r.request().postDataJSON().args[0] };
    return r.fulfill({ json: { result: true } });
  });
  await page.route("**/api/autosave", r => {
    workspace = r.request().postDataJSON().args[0];
    return r.fulfill({ json: { result: true } });
  });
  await page.goto("/#editor");
  const open = () => page.locator(".toolbar").getByRole("button", { name: "Project settings", exact: true }).click();
  await open();
  const dialog = page.getByRole("dialog", { name: "Project & application settings" });
  await dialog.getByRole("tab", { name: "Config", exact: true }).click();
  await expect(dialog.locator(".direction-current")).toContainText("Legacy custom look");
  await expect(dialog.getByLabel("Custom visual direction", { exact: true })).toHaveCount(0);
  await dialog.getByRole("button", { name: "Global config", exact: true }).click();
  await dialog.getByRole("radio", { name: /^Kurzgesagt-inspired/ }).click();
  await dialog.getByLabel("Reference influence", { exact: true }).selectOption("Strong");
  await expect.poll(() => (preferences.referenceConfig as any)?.referenceInfluence).toBe("Strong");
  await dialog.getByRole("button", { name: "Project config", exact: true }).click();
  await expect(dialog.locator(".direction-current")).toContainText("Legacy custom look");
  await dialog.getByRole("button", { name: "Copy global config to this project" }).click();
  await expect(dialog.locator(".direction-current")).toContainText("Kurzgesagt-inspired");
  await dialog.getByLabel("Reference influence", { exact: true }).selectOption("Subtle");
  await expect.poll(() => workspace.promptDraft?.referenceInfluence).toBe("Subtle");
  expect((preferences.referenceConfig as any).referenceNotes).toBe("Global blue");
  await page.screenshot({ path: "test-results/reference-project-config.png" });
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: "Prompts panel", exact: true }).click();
  const prompts = page.locator(".prompt-drawer");
  await expect(prompts.getByRole("tab", { name: "Reference look", exact: true })).toHaveCount(0);
  expect(await prompts.getByLabel("Generated prompt", { exact: true }).inputValue()).toContain("Reference influence: Subtle");
  await prompts.getByRole("button", { name: "Reset prompt fields", exact: true }).click();
  expect(await prompts.getByLabel("Generated prompt", { exact: true }).inputValue()).toContain("Reference influence: Subtle");
  await expect.poll(() => workspace.promptDraft?.script).toBe("");
  await page.reload();
  await open();
  await dialog.getByRole("tab", { name: "Config", exact: true }).click();
  await expect(dialog.getByLabel("Reference influence", { exact: true })).toHaveValue("Subtle");
  await expect(dialog.getByLabel("Custom visual direction", { exact: true })).toHaveCount(0);
  await page.setViewportSize({ width: 768, height: 900 });
  expect(await dialog.locator(".config-settings").evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: "test-results/reference-config-narrow.png" });
});

test("creating a project snapshots the global config", async ({ page }) => {
  const globalConfig = readReferenceConfig({ referenceStyle: "My default illustration", referenceInfluence: "Subtle", referenceNotes: "Warm colors" });
  let created: ReturnType<typeof newProject> | undefined;
  await page.route("**/api/settingsGet", r => r.fulfill({ json: { result: { referenceConfig: globalConfig } } }));
  await page.route("**/api/settingsSet", r => r.fulfill({ json: { result: true } }));
  await page.route("**/api/workspaceGet", r => r.fulfill({ json: { result: newProject() } }));
  await page.route("**/api/projectSave", r => {
    if (r.request().postDataJSON().args[1]?.create) created = r.request().postDataJSON().args[0];
    return r.fulfill({ json: { result: "created" } });
  });
  await page.goto("/");
  await page.getByRole("button", { name: "Application settings", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "Project & application settings" });
  await settings.getByRole("tab", { name: "Config", exact: true }).click();
  await expect(settings.getByRole("button", { name: "Project config", exact: true })).toBeDisabled();
  await expect(settings.locator(".direction-current")).toContainText("My default illustration");
  await settings.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: "Create project", exact: true }).first().click();
  const create = page.getByRole("dialog", { name: "Create project", exact: true });
  await create.getByLabel("New project name").fill("Inherited config");
  await create.getByRole("button", { name: "Create project", exact: true }).click();
  await expect.poll(() => created?.promptDraft).toEqual(globalConfig);
  await page.locator(".toolbar").getByRole("button", { name: "Project settings", exact: true }).click();
  await settings.getByRole("tab", { name: "Config", exact: true }).click();
  await settings.getByRole("button", { name: "Global config", exact: true }).click();
  await settings.getByRole("radio", { name: /^Kurzgesagt-inspired/ }).click();
  await settings.getByRole("button", { name: "Project config", exact: true }).click();
  await expect(settings.locator(".direction-current")).toContainText("My default illustration");
});

test("each card opens its own font settings without selecting the look", async ({ page }) => {
  let workspace = newProject();
  await page.route("**/api/workspaceGet", r => r.fulfill({ json: { result: workspace } }));
  await page.route("**/api/settingsGet", r => r.fulfill({ json: { result: {} } }));
  await page.route("**/api/settingsSet", r => r.fulfill({ json: { result: true } }));
  await page.route("**/api/autosave", r => {
    workspace = r.request().postDataJSON().args[0];
    return r.fulfill({ json: { result: true } });
  });
  await page.goto("/#editor");
  const open = () => page.locator(".toolbar").getByRole("button", { name: "Project settings", exact: true }).click();
  await open();
  const dialog = page.getByRole("dialog", { name: "Project & application settings" });
  await dialog.getByRole("tab", { name: "Config", exact: true }).click();
  await expect(dialog.getByRole("button", { name: /^Settings for / })).toHaveCount(29);
  await expect(dialog.locator(".direction-details").getByLabel("Reference look font")).toHaveCount(0);
  await dialog.getByRole("button", { name: "Settings for Vox-inspired", exact: true }).click();
  const popover = dialog.locator(".look-settings-popover:popover-open");
  await expect(popover.getByLabel("Reference look font")).toHaveValue("Outfit");
  await popover.getByLabel("Reference look font").selectOption("Georgia");
  await expect(dialog.getByRole("radio", { name: /^Original \/ no reference/ })).toHaveAttribute("aria-checked", "true");
  await expect(dialog.getByRole("radio", { name: /^Vox-inspired/ })).toHaveAttribute("aria-checked", "false");
  await page.screenshot({ path: "test-results/look-card-font-settings.png" });
  await popover.getByRole("button", { name: "Close look settings" }).click();
  await dialog.getByRole("button", { name: "Settings for Kurzgesagt-inspired", exact: true }).click();
  await expect(popover.getByLabel("Reference look font")).toHaveValue("Outfit");
  await popover.getByRole("button", { name: "Close look settings" }).click();
  await dialog.getByRole("button", { name: "Global config", exact: true }).click();
  await dialog.getByRole("button", { name: "Settings for Vox-inspired", exact: true }).click();
  await expect(popover.getByLabel("Reference look font")).toHaveValue("Outfit");
  await popover.getByRole("button", { name: "Close look settings" }).click();
  await dialog.getByRole("button", { name: "Project config", exact: true }).click();
  await dialog.getByRole("radio", { name: /^Vox-inspired/ }).click();
  await expect.poll(() => (workspace.promptDraft?.referenceLookSettings as any)?.[workspace.promptDraft?.referenceStyle as string]?.font).toBe("Georgia");
  await page.reload();
  await open();
  await dialog.getByRole("tab", { name: "Config", exact: true }).click();
  await dialog.getByRole("button", { name: "Settings for Vox-inspired", exact: true }).click();
  await expect(popover.getByLabel("Reference look font")).toHaveValue("Georgia");
  await popover.getByRole("button", { name: "Close look settings" }).click();
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: "Prompts panel", exact: true }).click();
  expect(await page.locator(".prompt-drawer").getByLabel("Generated prompt", { exact: true }).inputValue()).toContain("Reference look font: Georgia");
});
