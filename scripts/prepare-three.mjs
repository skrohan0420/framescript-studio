import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

// Bundle once as a string so preview, nested scenes and exported HTML share the
// exact same offline runtime. No origin privileges or CDN access are required.
const result = await build({
  stdin: {
    contents: 'import * as THREE from "three"; window.THREE = THREE;',
    resolveDir: process.cwd(),
  },
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  minify: true,
  legalComments: "inline",
  target: "es2022",
});
await writeFile(
  "shared/three-source.generated.ts",
  "// Generated by scripts/prepare-three.mjs; includes Three.js MIT license.\nexport const threeSource = " +
    JSON.stringify(result.outputFiles[0].text) +
    ";\n",
);
